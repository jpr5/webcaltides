"""Write data/datums/t1g_gap_patterns.json (datums spec §5.2 T1g, sealed in slot DT0b).

Each pattern's seed is the first 8 bytes (unsigned big-endian) of SHA-256('otc-datums-t1g-v1|' + letter).
Usage: python tools/t1g_gap_patterns.py OUT_JSON   (rebuilds the sealed file byte for byte)
"""
import hashlib
import json
import sys
from pathlib import Path

NOT_STATED = "not stated in §5.2 (only (d) is restricted to the short station); DT1 decides"
PATTERNS = {
    "a": {"description": "20 random gaps of 3 h per month", "gaps_per_month": 20, "gap_hours": 3, "applies_to": NOT_STATED},
    "b": {"description": "5 random gaps of 12 h per month", "gaps_per_month": 5, "gap_hours": 12, "applies_to": NOT_STATED},
    "c": {"description": "one 48-h gap per month", "gaps_per_month": 1, "gap_hours": 48, "applies_to": NOT_STATED},
    "d": {"description": "10% of hours dropped at random, at the short station only", "fraction_of_hours": 0.10,
          "applies_to": "short station only"},
}
RULE = ("datums spec §5.2 T1g gap injection: gap patterns (a)-(d) as written there; each pattern's seed is "
        "the first 8 bytes (unsigned big-endian) of SHA-256('otc-datums-t1g-v1|' + pattern letter), fixed in "
        "DT0b before any T1 data is reduced. How a seed is expanded into gap positions (RNG, month "
        "boundaries, overlap) is defined by the T1g harness (DT1) and is not part of this seal.")
NOTES = [
    "Deviation (seed expansion left to DT1): §5.2 says the gap patterns are 'seeded and committed'. This file "
    "seals the seeds and the pattern parameters only; DT1 commits the seed-to-gap expansion code and the hash "
    "of its output before any T1g score is computed.",
    "Deviation: whether patterns (a)-(c) apply to the short station, the control or both is not stated in §5.2; "
    "DT1 decides and records it.",
    "Generated by scripts/otc/tools/t1g_gap_patterns.py.",
]


def build() -> str:
    pats = {k: dict(v, seed=int.from_bytes(hashlib.sha256(f"otc-datums-t1g-v1|{k}".encode()).digest()[:8], "big"))
            for k, v in PATTERNS.items()}
    return json.dumps({"notes": NOTES, "patterns": pats, "rule": RULE, "year": 2015}, indent=1, sort_keys=True) + "\n"


if __name__ == "__main__":
    Path(sys.argv[1]).write_text(build())
